// Runs on the audio thread: batches microphone samples into ~2048-sample frames and posts them to the page,
// where the voice-activity detector and WAV encoder run. Nothing leaves the device from here.
class LexaCapture extends AudioWorkletProcessor {
  constructor() {
    super();
    this.buf = new Float32Array(2048);
    this.n = 0;
  }
  process(inputs) {
    const channel = inputs[0] && inputs[0][0];
    if (channel) {
      for (let i = 0; i < channel.length; i++) {
        this.buf[this.n++] = channel[i];
        if (this.n === this.buf.length) {
          this.port.postMessage(this.buf.slice(0));
          this.n = 0;
        }
      }
    }
    return true;
  }
}
registerProcessor("lexa-capture", LexaCapture);
